export const GLYPH_HEIGHT = 7;

function glyph(ch) {
  return G[ch] ?? G[ch.toUpperCase()] ?? G['?'];
}

/** Width in pixels of `str` drawn at `scale`, with one empty column between glyphs. */
export function textWidth(str, scale = 1, spacing = 1) {
  let w = 0;
  const chars = [...str];
  chars.forEach((ch, i) => {
    w += glyph(ch)[0].length;
    if (i < chars.length - 1) w += spacing;
  });
  return w * scale;
}

/** Path data for `str` with its top left corner at (x, y). */
export function textD(str, x, y, scale = 1, spacing = 1) {
  let d = '';
  let cx = x;
  for (const ch of str) {
    const rows = glyph(ch);
    rows.forEach((row, ry) => {
      let i = 0;
      while (i < row.length) {
        if (row[i] !== '#') { i++; continue; }
        let e = i;
        while (e < row.length && row[e] === '#') e++;
        d += `M${r(cx + i * scale)} ${r(y + ry * scale)}h${r((e - i) * scale)}v${r(scale)}h${r(-(e - i) * scale)}z`;
        i = e;
      }
    });
    cx += (rows[0].length + spacing) * scale;
  }
  return d;
}

/**
 * A <path> drawing `str`. `anchor` is start, middle or end, measured from x.
 * Extra attributes (class, style, opacity) go in `attrs`.
 */
export function text(str, x, y, scale, fill, { anchor = 'start', spacing = 1, attrs = '' } = {}) {
  const w = textWidth(str, scale, spacing);
  const sx = anchor === 'middle' ? Math.round(x - w / 2) : anchor === 'end' ? x - w : x;
  return `<path fill="${fill}" ${attrs} d="${textD(str, sx, y, scale, spacing)}"/>`;
}

/** Split `str` into lines no wider than `maxWidth` pixels at `scale`. */
export function wrap(str, maxWidth, scale = 1) {
  const words = str.split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (textWidth(next, scale) <= maxWidth || !line) line = next;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines;
}

function r(n) {
  return Math.round(n * 100) / 100;
}
